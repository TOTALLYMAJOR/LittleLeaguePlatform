function daysFromNow(days, hour, minute = 0) {
  const value = new Date();
  value.setUTCDate(value.getUTCDate() + days);
  value.setUTCHours(hour, minute, 0, 0);
  return value.toISOString();
}

function nowIso() {
  return new Date().toISOString();
}

async function findUserByEmail(supabase, email) {
  let page = 1;
  const perPage = 200;

  while (page < 20) {
    const { data, error } = await supabase.auth.admin.listUsers({ page, perPage });
    if (error) throw error;
    const found = data.users.find((user) => user.email?.toLowerCase() === email.toLowerCase());
    if (found) return found;
    if (data.users.length < perPage) return null;
    page += 1;
  }

  return null;
}

async function upsertAuthUser(supabase, input) {
  const existing = await findUserByEmail(supabase, input.email);
  if (existing) {
    const { data, error } = await supabase.auth.admin.updateUserById(existing.id, {
      password: input.password,
      email_confirm: true,
      user_metadata: {
        display_name: input.displayName,
        default_role: input.defaultRole,
        demo_tenant: "leaguepilot-product-demo"
      }
    });
    if (error) throw error;
    return data.user;
  }

  const { data, error } = await supabase.auth.admin.createUser({
    email: input.email,
    password: input.password,
    email_confirm: true,
    user_metadata: {
      display_name: input.displayName,
      default_role: input.defaultRole,
      demo_tenant: "leaguepilot-product-demo"
    }
  });
  if (error) throw error;
  return data.user;
}

async function upsertOrThrow(supabase, table, row, options = {}) {
  const { data, error } = await supabase
    .from(table)
    .upsert(row, { onConflict: "id", ...options })
    .select("id")
    .single();
  if (error) throw new Error(`${table} upsert failed: ${error.message}`);
  return data;
}

async function updateOrThrow(supabase, table, values, column, value) {
  const { data, error } = await supabase
    .from(table)
    .update(values)
    .eq(column, value)
    .select("id")
    .single();
  if (error) throw new Error(`${table} update failed: ${error.message}`);
  return data;
}

async function upsertDeliveryAttemptOrFallback(supabase, row) {
  try {
    return await upsertOrThrow(supabase, "notification_delivery_attempts", row);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (!message.includes("Could not find") && !message.includes("schema cache")) {
      throw error;
    }

    console.warn("Delivery execution metadata columns are not available; writing base demo delivery attempt row only.");
    const {
      id,
      notification_id,
      provider,
      provider_message_id,
      channel,
      status,
      error_code,
      error_message,
      attempted_at
    } = row;
    return upsertOrThrow(supabase, "notification_delivery_attempts", {
      id,
      notification_id,
      provider,
      provider_message_id,
      channel,
      status,
      error_code,
      error_message,
      attempted_at
    });
  }
}

